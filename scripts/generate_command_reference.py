#!/usr/bin/env python3
"""Rebuild docs/reference/commands.md from the Typer app.

The command table used to be hand-maintained and drifted after every new
command. This script walks the Click tree of ``ksef2_cli.app.app`` and writes
the whole reference, so the checked-in file is only ever as fresh as the code.

Run ``python scripts/generate_command_reference.py`` after changing commands;
``--check`` exits non-zero when the committed file is stale. Output is
deterministic: command order follows what ``ksef2 --help`` prints and help
text is taken verbatim, never terminal-wrapped.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import click
import typer

from ksef2_cli.app import app as typer_app

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = REPO_ROOT / "docs" / "reference" / "commands.md"

# Added by Click/Typer to every app, so repeating them per section is noise.
EXCLUDED_PARAMS = {"help", "install_completion", "show_completion"}

HEADER = """---
title: Command Reference
description: Command groups and subcommands exposed by KSeF2 CLI.
---

This page is generated by `scripts/generate_command_reference.py` from the
Typer app. Run that script after adding, removing, or changing a command or
option; a test fails when the committed file goes stale.

Global options must be placed before the command group:

```bash
ksef2 [GLOBAL OPTIONS] COMMAND [ARGS]...
```
"""


def render(root: click.Command | None = None) -> str:
    lines: list[str] = [HEADER]
    root = root or typer.main.get_command(typer_app)

    lines.append("## Global options\n")
    lines.extend(_option_table(root.params))

    lines.append("## Command groups\n")
    lines.append("| Group | Purpose |")
    lines.append("| --- | --- |")
    for name, command in _subcommands(root):
        lines.append(f"| `{name}` | {_cell(_summary(command))} |")
    lines.append("")

    for group_name, group in _subcommands(root):
        lines.append(f"## `{group_name}`\n")
        summary = _summary(group)
        if summary and group.callback is not None:
            lines.append(f"{summary}\n")
        for command_name, command in _subcommands(group):
            full = f"{group_name} {command_name}"
            lines.append(f"### `{full}`\n")
            usage = _usage(full, command)
            if usage != f"ksef2 {full} [OPTIONS]":
                lines.append(f"Usage: `{usage}`\n")
            help_text = (command.help or "").strip()
            if help_text:
                lines.append(f"{help_text}\n")
            lines.extend(_option_table(command.params))

    return "\n".join(lines).rstrip("\n") + "\n"


def command_tree(root: click.Command | None = None) -> list[tuple[str, click.Command]]:
    """Every command and subgroup as (path, command), in ``--help`` order."""
    root = root or typer.main.get_command(typer_app)
    found: list[tuple[str, click.Command]] = []

    def walk(group: click.Group, prefix: str) -> None:
        for name, command in _subcommands(group):
            path = f"{prefix}{name}"
            found.append((path, command))
            if isinstance(command, click.Group):
                walk(command, f"{path} ")

    walk(root, "")
    return found


def _subcommands(group: click.Group) -> list[tuple[str, click.Command]]:
    ctx = click.Context(group)
    return [(name, group.get_command(ctx, name)) for name in group.list_commands(ctx)]


def _usage(prefix: str, command: click.Command) -> str:
    parts = [f"ksef2 {prefix}"]
    if any(isinstance(param, click.Option) for param in command.params):
        parts.append("[OPTIONS]")
    for param in command.params:
        if isinstance(param, click.Argument):
            parts.append(param.make_metavar())
    return " ".join(parts)


def _option_table(params: list[click.Parameter]) -> list[str]:
    rows: list[str] = []
    for param in params:
        if param.hidden or param.name in EXCLUDED_PARAMS:
            continue
        if isinstance(param, click.Option):
            flags = ", ".join(f"`{flag}`" for flag in _option_flags(param))
        else:
            flags = f"`{param.make_metavar()}`"
        rows.append(
            "| "
            + " | ".join(
                [
                    flags,
                    _cell(_type_label(param)),
                    _cell(_default_label(param)),
                    _cell(", ".join(_envvars(param)) or "-"),
                    _cell(param.help or "-"),
                ]
            )
            + " |"
        )
    if not rows:
        return []
    return [
        "| Option | Type | Default | Env var | Help |",
        "| --- | --- | --- | --- | --- |",
        *rows,
        "",
    ]


def _type_label(param: click.Parameter) -> str:
    if isinstance(param, click.Argument):
        return "-"  # The Flags column already names the argument.
    if isinstance(param, click.Option) and param.is_flag:
        return "-"  # A flag takes no value.
    return param.make_metavar()


def _option_flags(option: click.Option) -> list[str]:
    return [*option.opts, *option.secondary_opts]


def _envvars(param: click.Parameter) -> list[str]:
    envvar = param.envvar
    if envvar is None:
        return []
    return list(envvar) if isinstance(envvar, (list, tuple)) else [envvar]


def _default_label(param: click.Parameter) -> str:
    if param.required:
        return "required"
    default = param.default
    if default is None or default == ():
        return "-"
    if isinstance(default, bool):
        return str(default).lower()
    if hasattr(default, "value"):  # Enum default: keep it deterministic.
        return str(default.value)
    return str(default)


def _summary(command: click.Command) -> str:
    text = (command.short_help or command.help or "").strip()
    return text.splitlines()[0] if text else ""


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when the file is stale")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()

    content = render()
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding="utf-8") != content:
            print(
                f"{args.output.relative_to(REPO_ROOT)} is stale; "
                "run scripts/generate_command_reference.py",
                file=sys.stderr,
            )
            return 1
        return 0

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(content, encoding="utf-8")
    print(f"wrote {args.output.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
