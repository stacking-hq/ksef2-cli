"""Keep docs/reference/commands.md in sync with the Typer app.

The file is generated by scripts/generate_command_reference.py. These tests
run the same generator in memory: one fails on any drift, one proves drift is
detected at all, and one checks the page covers every command the CLI lists.
"""

import importlib.util
from pathlib import Path

import pytest
import typer

from ksef2_cli.app import app

ROOT = Path(__file__).resolve().parents[2]
REFERENCE = ROOT / "docs" / "reference" / "commands.md"

_spec = importlib.util.spec_from_file_location(
    "generate_command_reference", ROOT / "scripts" / "generate_command_reference.py"
)
assert _spec and _spec.loader
generator = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(generator)


def test_reference_matches_generated_output() -> None:
    assert REFERENCE.read_text(encoding="utf-8") == generator.render(), (
        "docs/reference/commands.md is stale; run scripts/generate_command_reference.py"
    )


def test_generator_notices_a_changed_help_text() -> None:
    root = typer.main.get_command(app)
    before = generator.render(root)
    option = next(
        param
        for param in dict(generator.command_tree(root))["auth login"].params
        if param.name == "save_state"
    )
    option.help = "Silently reworded help text."
    assert generator.render(root) != before


@pytest.mark.parametrize("path", [path for path, _ in generator.command_tree()])
def test_every_command_has_a_section(path: str) -> None:
    text = REFERENCE.read_text(encoding="utf-8")
    if " " not in path:
        assert f"\n## `{path}`\n" in text, f"missing group section for {path}"
    else:
        assert f"\n### `{path}`\n" in text, f"missing section for {path}"
